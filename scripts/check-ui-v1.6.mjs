import {readFileSync} from 'node:fs';import {Script} from 'node:vm';import assert from 'node:assert/strict';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('index.html'),css=read('ui-v1.6.css'),nav=read('navigation-v1.6.js'),ai=read('ai-dictionary.js'),dictionary=read('dictionary.js');
for(const p of ['navigation-v1.6.js','ai-dictionary.js','dictionary.js'])new Script(read(p),{filename:p});
assert.match(html,/href="ui-v1\.6\.css\?v=160"/);
assert.match(html,/src="navigation-v1\.6\.js\?v=160"/);
assert.ok(html.indexOf('src="dictionary.js"')<html.indexOf('src="ai-dictionary.js"'));
assert.ok(html.indexOf('src="ai-dictionary.js"')<html.indexOf('src="navigation-v1.6.js'));
for(const tab of ['home','calc','quiz','cases','notes'])assert.ok(html.includes('data-tab="'+tab+'"'),'Missing tab '+tab);
for(const model of ['gpt-6-luna','gpt-4.1-mini','gpt-4.1'])assert.ok(ai.includes(model),'Missing model '+model);
assert.ok(ai.includes('KEY="fse_ai_dictionary_v1_4"'));
assert.ok(dictionary.includes('KEY="fse_dictionary_v1_3"'));
assert.ok(nav.includes('setTimeout(sync,0)'),'More-menu state must update after render');
assert.ok(nav.includes('document.head.append(theme)'),'Legacy injected styles must be overridden');
assert.ok(css.includes('.fse-nav-secondary{display:none'));
assert.ok(css.includes('prefers-reduced-motion'));
assert.ok(css.includes('env(safe-area-inset-bottom)'));
assert.ok(!/OPENAI_API_KEY|TURNSTILE_SECRET/.test(css+nav),'Secrets must not appear in UI assets');
console.log('PASS: v1.6 asset wiring, syntax, model compatibility, storage keys and nav invariants');
